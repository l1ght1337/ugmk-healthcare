@dataclass(frozen=True)
class Faq:
    group: str
    question: str
    source: str
    kind: str  # route type: clinic_question, complaint, medical_question, …
    answer: str  # what the patient reads (in short)
    facts: tuple[str, ...] = ()  # kb/info, config: fragments of the справка the answer uses
    scenario: str | None = None  # сценарий: the scenario route picks
    action: str | None = None  # menu_action / a typed command
    command: bool = False  # caught by the word list in code (no DeepSeek)
    live: bool = False  # the group's live DeepSeek test (tests/test_llm_live.py)


def q(group: str, question: str, source: str, answer: str, **kw: object) -> Faq:
    kind = kw.pop("kind", None) or {
        KB: "clinic_question", CONFIG: "clinic_question", NO_DATA: "clinic_question",
        SCENARIO: "complaint",
    }.get(source, "")  # fmt: skip
    return Faq(group, question, source, str(kind), answer, **kw)  # type: ignore[arg-type]


