def summary() -> Counter[str]:
    return Counter(
        "данные" if f.source in DATA_SOURCES else "шаблон" if f.source == TEMPLATE else "нет данных"
        for f in FAQS
    )


def render_doc() -> str:
    totals = summary()
    lines = [
        "# Вопросы пациентов и ответы бота",
        "",
        "Файл собирается из `tests/faq_cases.py` командой `uv run python -m tests.faq_cases "
        "--write`; те же вопросы проверяет `tests/test_faq.py` (ответ по нужной ветке, данные "
        "есть в справке), а по одному вопросу на группу — живой DeepSeek (`uv run pytest -m "
        "live`).",
        "",
        "Источник ответа: **kb/info** и **config** — справка и настройки клиники (DeepSeek "
        "отвечает только по ним); **сценарий** — сценарий из `kb/scenarios`; **шаблон** — "
        "постоянная фраза бота или экран меню; **нет данных** — бот честно говорит «У меня "
        "нет этой информации» и предлагает передать вопрос администратору (список таких "
        "вопросов — в `docs/clinic_requests.md`).",
        "",
        f"Всего вопросов: {len(FAQS)}. Закрыто данными: {totals['данные']}, шаблоном: "
        f"{totals['шаблон']}, данных нет: {totals['нет данных']}.",
        "",
    ]
    groups = list(dict.fromkeys(f.group for f in FAQS))
    for group in groups:
        lines += [f"## {group}", "", "| Вопрос | Источник | Что отвечает бот |", "|---|---|---|"]
        for f in FAQS:
            if f.group == group:
                lines.append(f"| {f.question} | {f.source} | {f.answer} |")
        lines.append("")
    return "\n".join(lines)


