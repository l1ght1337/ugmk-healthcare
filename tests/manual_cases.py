"""The 20 acceptance cases as steps: one source for docs/manual_test.md and the test run.

    uv run python -m tests.manual_cases --write    # regenerate docs/manual_test.md

In the test (tests/test_manual_cases.py) DeepSeek is replaced by canned replies (``llm``);
in Telegram the real DeepSeek answers, so wording may differ — ``hint`` says what to press
if the bot asks a question the canned run did not need.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from pathlib import Path

DOC = Path(__file__).resolve().parent.parent / "docs" / "manual_test.md"


def route(scenario: str, **facts: object) -> dict:
    return {"type": "complaint", "scenario": scenario, "facts": facts}


def answer(text: str | None, offer_admin: bool = False) -> dict:
    return {"found": text is not None, "answer": text, "offer_admin": offer_admin}


QUESTION = {"type": "clinic_question"}  # route: a question about the trauma centre


@dataclass(frozen=True)
class Step:
    do: str  # start menu say press slot contact demo_until admin forget
    value: str = ""
    expect: tuple[str, ...] = ()  # fragments of the bot's reply
    absent: tuple[str, ...] = ()  # fragments that must not be in it
    admin: tuple[str, ...] = ()  # fragments of the new post in the admin chat
    hint: str = ""
    llm: tuple[dict, ...] = ()  # canned DeepSeek replies, tests only
    private: bool = False  # nothing personal may reach DeepSeek on this step


@dataclass(frozen=True)
class Case:
    number: str
    title: str
    steps: tuple[Step, ...]
    note: str = ""
    extra: bool = field(default=False)  # beyond the 20 acceptance cases


