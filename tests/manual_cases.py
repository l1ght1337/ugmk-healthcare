def _instruction(step: Step) -> str:
    if step.do == "say":
        return f"Напишите: «{step.value}»"
    if step.do == "press":
        return f"Нажмите «{step.value}»"
    if step.do == "demo_until":
        return f"Отправляйте /demo_next, пока не придёт «{step.value}»"
    if step.do == "admin":
        return f"В чате администраторов ответьте реплаем на сообщение бота: «{step.value}»"
    return _DO[step.do]


