def _instruction(step: Step) -> str:
    if step.do == "say":
        return f"Напишите: «{step.value}»"
    if step.do == "press":
        return f"Нажмите «{step.value}»"
    if step.do == "demo_until":
        return f"Отправляйте /demo_next, пока не придёт «{step.value}»"
    if step.do == "admin":
        return f"В чате администраторов ответьте реплаем на сообщение бота: «{step.value}»"
    return _DO[step.do]


def render_doc() -> str:
    lines = [
        "# Ручной прогон в Telegram",
        "",
        "Файл собирается из `tests/manual_cases.py` командой "
        "`uv run python -m tests.manual_cases --write`; те же шаги прогоняет "
        "`tests/test_manual_cases.py` (с подставленными ответами DeepSeek).",
        "",
        "## Подготовка",
        "1. В `.env`: `DEMO_MODE=true`, `SCHEDULE_PROVIDER=mock`, Ваш Telegram ID в "
        "`ALLOWED_USER_IDS`, бот добавлен в группу `ADMIN_CHAT_ID`.",
        "2. Запустите бота: `uv run python -m app`.",
        "3. Отправьте боту /forget → «Да, удалить», чтобы начать с чистого листа.",
        "4. Проходите кейсы по порядку одним аккаунтом: согласие и телефон даются в кейсе 1, "
        "кейсы 17–18 продолжают запись из кейса 1.",
        "5. В прогоне больше трёх обращений к администратору за день, поэтому на время прогона "
        "поставьте в `.env` `HANDOFF_DAILY_LIMIT=10` (обычно — 3 в сутки).",
        "",
        "Ответы DeepSeek могут отличаться формулировками. Если бот задаёт уточняющий вопрос, "
        "отвечайте кнопкой по смыслу кейса — подсказки в скобках. «Должно прийти» — фрагменты, "
        "которые должны быть в ответе бота.",
        "",
    ]
    for case in CASES:
        if case.extra and not any(c.extra for c in CASES[: CASES.index(case)]):
            lines += ["## Дополнительно", ""]
        lines.append(f"### {case.number}. {case.title}")
        for i, step in enumerate(case.steps, 1):
            text = f"{i}. {_instruction(step)}"
            if step.hint:
                text += f" ({step.hint})"
            if step.expect:
                text += ". Должно прийти: " + ", ".join(f"«{e}»" for e in step.expect)
            if step.admin:
                text += ". В чат администраторов: " + ", ".join(f"«{a}»" for a in step.admin)
            lines.append(text.replace("\n", " ") + ("" if text.endswith(".") else "."))
        if case.note:
            lines.append(f"\n_{case.note}_")
        lines.append("")
    lines += [
        "### 23. Дополнительно: доступ для сотрудника клиники",
        "Нужен второй аккаунт, которого нет в `ALLOWED_USER_IDS` (проверка автоматически — "
        "`tests/test_telegram.py`).",
        "1. Со второго аккаунта отправьте боту /start. Должно прийти: «тестовом режиме», "
        "«передал запрос администраторам». В чат администраторов: имя, @username и Telegram id "
        "с кнопкой «Разрешить».",
        "2. В чате администраторов нажмите «Разрешить». Под запросом появится «Доступ открыт», "
        "второму аккаунту придёт «Доступ к тестовому боту открыт».",
        "3. Со второго аккаунта отправьте /start — бот отвечает как обычно.",
        "",
    ]
    return "\n".join(lines)


